s = input().strip()

try:
    n = int(s)
except ValueError:
    print("ошибка: поддерживаются только целые числа")
    exit()

sign = -1 if n < 0 else 1
n = abs(n)

rev = 0
while n > 0:
    rev = rev * 10 + n % 10
    n //= 10

print(sign * rev)

